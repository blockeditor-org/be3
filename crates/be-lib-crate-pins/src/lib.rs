//! The crates Cargo.lock names from crates.io, and [`DOWNLOADS_PATH`], which
//! pins each by its SHA-256 and size for buck2 to download
//! (buck/cargo/third_party.bzl). crates/be-tool-bootstrap's lock step writes it
//! after bringing Cargo.lock up to date ([`render`]), and buckify's action
//! (crates/be-tool-cargo-offline) vendors what it pins for cargo. Also the
//! members index buckify writes ([`MEMBERS_PATH`]), which the bootstrap checks
//! against the crates on disk.

use std::collections::BTreeMap;

/// The downloads table, which only the lock step writes.
pub const DOWNLOADS_PATH: &str = "third-party/rust/downloads.bzl";

/// What the table starts with, on a line of its own after the header.
pub const DOWNLOADS: &str = "downloads = ";

/// Every workspace crate's directory, which crates/be-tool-buck's generate
/// writes and buck/cargo/defs.bzl and BUCK.v2 read.
pub const MEMBERS_PATH: &str = "buck/cargo/members.bzl";

const MEMBERS: &str = "members = [\n";

/// The members index for these crate directories, `crates/NAME`.
pub fn render_members(members: &[String]) -> String {
    let mut text = format!(
        "# @generated by ./scripts/buckify from the workspace's Cargo.toml files\n\
         # (crates/be-tool-buck's generate): every workspace crate.\n\n{MEMBERS}"
    );
    for member in members {
        text.push_str(&format!("    \"{member}\",\n"));
    }
    text.push_str("]\n");
    text
}

/// The crate directories a members index names.
pub fn members(index: &str) -> Vec<String> {
    index
        .lines()
        .skip_while(|line| *line != MEMBERS.trim_end())
        .filter_map(|line| line.strip_prefix("    \"")?.strip_suffix("\","))
        .map(str::to_owned)
        .collect()
}

/// A crate Cargo.lock names with a checksum: one from crates.io.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Locked {
    pub name: String,
    pub version: String,
    pub sha256: String,
}

impl Locked {
    /// Where crates.io serves the archive whose SHA-256 is [`Locked::sha256`].
    pub fn url(&self) -> String {
        format!(
            "https://static.crates.io/crates/{name}/{name}-{version}.crate",
            name = self.name,
            version = self.version
        )
    }
}

/// Every crate Cargo.lock names with a checksum, by `name-version`.
pub fn locked(lock: &str) -> BTreeMap<String, Locked> {
    let mut found = BTreeMap::new();
    let mut name = "";
    let mut version = "";
    for line in lock.lines().map(str::trim) {
        let value = |prefix: &str| {
            line.strip_prefix(prefix)
                .map(|rest| rest.trim().trim_matches('"'))
        };
        if line == "[[package]]" {
            name = "";
            version = "";
        } else if let Some(value) = value("name =") {
            name = value;
        } else if let Some(value) = value("version =") {
            version = value;
        } else if let Some(value) = value("checksum =") {
            found.insert(
                format!("{name}-{version}"),
                Locked {
                    name: name.to_owned(),
                    version: version.to_owned(),
                    sha256: value.to_owned(),
                },
            );
        }
    }
    found
}

/// The size each entry of a downloads table pins, by key.
pub fn pinned_sizes(downloads: &str) -> BTreeMap<String, u64> {
    let mut sizes = BTreeMap::new();
    let mut key = None;
    for line in downloads.lines() {
        if let Some(name) = line
            .strip_prefix("    \"")
            .and_then(|rest| rest.strip_suffix("\": {"))
        {
            key = Some(name.to_owned());
        } else if let Some(size) = line
            .trim()
            .strip_prefix("\"size_bytes\": ")
            .and_then(|rest| rest.trim_end_matches(',').parse().ok())
            && let Some(key) = key.take()
        {
            sizes.insert(key, size);
        }
    }
    sizes
}

/// The downloads table for every crate Cargo.lock names, built for some
/// platform or not, since cargo reads the whole lockfile, as the whole file.
/// Every one needs its size in `sizes`.
pub fn render(
    locked: &BTreeMap<String, Locked>,
    sizes: &BTreeMap<String, u64>,
) -> Result<String, String> {
    let mut text = format!(
        "# @generated by the bootstrap's lock step (crates/be-tool-bootstrap/src/lock.rs)\n\
         # from Cargo.lock: every crate it names from crates.io, pinned by hash and size.\n\n\
         {DOWNLOADS}{{\n"
    );
    for (key, crate_) in locked {
        let size = sizes
            .get(key)
            .ok_or_else(|| format!("no size for {key}, which Cargo.lock names"))?;
        for value in [key, &crate_.name, &crate_.version, &crate_.sha256] {
            if !value
                .chars()
                .all(|character| character.is_ascii_alphanumeric() || "._+-".contains(character))
            {
                return Err(format!("Cargo.lock names a crate as {value:?}"));
            }
        }
        text.push_str(&format!(
            "    \"{key}\": {{\n        \"name\": \"{}\",\n        \"sha256\": \"{}\",\n        \"size_bytes\": {size},\n        \"version\": \"{}\",\n    }},\n",
            crate_.name, crate_.sha256, crate_.version
        ));
    }
    text.push_str("}\n");
    Ok(text)
}

