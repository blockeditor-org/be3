use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use be_lib_prompt::{Choice, Saved, choose, config_directory, interactive, save_private, text};

use crate::{Result, repository};

/// `nl.be3.pfg.pw`, our NativeLink server; `custom`, a NativeLink server of your own at host:port; `local`, this
/// machine (guides/running/local_buck2.md).
const SERVERS: [&str; 3] = ["nl.be3.pfg.pw", "custom", "local"];
const MARKER: &str = "# @generated by ./scripts/buck: where buck2 reaches the build server.";

/// Where buck2 reaches the build server, which .buckconfig includes if it
/// exists. A person's .buckconfig.local is read after it, and is never written.
pub const GENERATED: &str = "target/build-server.buckconfig";

pub fn configure(buck2: &Path) -> Result<()> {
    let path = repository().join(GENERATED);
    if std::fs::exists(repository().join(".buckconfig.local")).unwrap_or(false) {
        // A person's: buck2 builds where it says, on the build server it names
        // or here, and the generated addresses and header would only be mixed
        // into theirs.
        if std::fs::remove_file(&path).is_ok() {
            kill_daemon(buck2);
        }
        return Ok(());
    }
    let server = server()?;
    let mut config = String::new();
    let _ = writeln!(config, "{MARKER}");
    if server == "local" {
        // As guides/running/local_buck2.md says, with two rustc threads.
        let _ = writeln!(config, "# This machine.");
        let _ = writeln!(config, "[build]");
        let _ = writeln!(
            config,
            "execution_platforms = root//buck/platforms:execution_platforms_local"
        );
        let _ = writeln!(config, "[buck2_re_client]");
        let _ = writeln!(config, "enabled = false");
        let _ = writeln!(config, "[fbcode]");
        let _ = writeln!(config, "disable_re_tests = true");
        let _ = writeln!(config, "[be3]");
        let _ = writeln!(config, "rustc_threads = 2");
    } else {
        let (engine, header, mut address, mut storage, mut tls);
        if server == "custom" {
            engine = custom_address()?;
            address = engine.clone();
            storage = engine.clone();
            header = String::new();
            tls = false;
        } else {
            // Caddy in front of NativeLink checks `Authorization: Bearer TOKEN` (scripts/internal/nativelink). With no
            // key buck2 sends no header, for a cloud session's proxy, which adds it.
            engine = server.clone();
            address = format!("{engine}:443");
            storage = address.clone();
            header = bearer_header(&server);
            tls = true;
            if proxy() {
                // Caddy also serves re-relay's tunnel, which carries every call inside a few long requests for a proxy
                // that handles few requests a second (a cloud session's). BE3_NL_TUNNEL=0 sends each call as its own
                // request instead.
                let tunnel = std::env::var("BE3_NL_TUNNEL").as_deref() != Ok("0");
                (address, storage) = relay::ensure(&engine, tunnel)?;
                tls = false;
            }
        }
        let _ = writeln!(config, "# The server: {engine}");
        let _ = writeln!(config, "[buck2_re_client]");
        let _ = writeln!(config, "action_cache_address = {storage}");
        let _ = writeln!(config, "cas_address = {storage}");
        let _ = writeln!(config, "engine_address = {address}");
        if !header.is_empty() {
            let _ = writeln!(config, "http_headers = {header}");
        }
        let _ = writeln!(config, "tls = {tls}");
    }
    if std::fs::read(&path).is_ok_and(|existing| existing == config.as_bytes()) {
        return Ok(());
    }
    write_private(&path, &config)?;
    kill_daemon(buck2);
    Ok(())
}

fn proxy() -> bool {
    ["HTTPS_PROXY", "https_proxy"]
        .iter()
        .any(|name| std::env::var(name).is_ok_and(|value| !value.is_empty()))
}

/// buck2 reads its remote execution settings only when its daemon starts.
fn kill_daemon(buck2: &Path) {
    let _ = Command::new(buck2)
        .arg("kill")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
}

fn write_private(path: &Path, text: &str) -> Result<()> {
    save_private(path, text).map_err(|error| format!("could not write {}: {error}", path.display()))
}

fn saved_server_file() -> PathBuf {
    config_directory().join("build-server")
}

fn saved_lines() -> Vec<String> {
    std::fs::read_to_string(saved_server_file())
        .unwrap_or_default()
        .lines()
        .map(|line| {
            line.chars()
                .filter(|character| !character.is_whitespace())
                .collect()
        })
        .collect()
}

fn server() -> Result<String> {
    let saved = saved_server_file();
    let mut server = std::env::var("BE3_BUILD_SERVER").unwrap_or_default();
    if server.is_empty() {
        server = saved_lines().into_iter().next().unwrap_or_default();
    }
    if server.is_empty() {
        server = ask_for_server(&saved).unwrap_or_default();
    }
    if server.is_empty() {
        server = SERVERS[0].to_owned();
    }
    if SERVERS.contains(&server.as_str()) {
        return Ok(server);
    }
    Err(format!(
        "The build server is {server}, which is none of {}.\nBE3_BUILD_SERVER or {} picks it.",
        SERVERS.join(" "),
        saved.display()
    ))
}

fn ask_for_server(saved: &Path) -> Option<String> {
    let choices: Vec<Choice> = SERVERS
        .iter()
        .map(|server| Choice {
            label: server,
            detail: match *server {
                "nl.be3.pfg.pw" => "our NativeLink build server (needs its token)",
                "custom" => "a NativeLink server of your own, without TLS or a key",
                _ => "this machine, with no build server",
            },
        })
        .collect();
    if interactive() {
        eprintln!("guides/build_server.md says more about each.");
    }
    let server = SERVERS[choose("Where should buck2 build?", &choices, 0)?];
    let mut text = format!("{server}\n");
    if server == "custom" {
        text.push_str(&format!("{}\n", ask_for_custom_address()?));
    }
    save(saved, &text);
    eprintln!(
        "Saved it to {}; delete it to be asked again.",
        saved.display()
    );
    Some(server.to_owned())
}

fn save(path: &Path, text: &str) {
    if let Err(error) = write_private(path, text) {
        eprintln!("{error}");
    }
}

fn is_address(address: &str) -> bool {
    address.split_once(':').is_some_and(|(host, port)| {
        !host.is_empty()
            && !host.contains('/')
            && !port.is_empty()
            && port.chars().all(|character| character.is_ascii_digit())
    })
}

fn ask_for_custom_address() -> Option<String> {
    text("NativeLink address:", "127.0.0.1:50052", |address| {
        let address = address.strip_prefix("grpc://").unwrap_or(address);
        if is_address(address) {
            Ok(address.to_owned())
        } else {
            Err("That is not a host:port.".to_owned())
        }
    })
}

fn custom_address() -> Result<String> {
    let mut address = std::env::var("BE3_BUILD_SERVER_ADDRESS").unwrap_or_default();
    let saved = saved_lines();
    if address.is_empty() && saved.first().is_some_and(|server| server == "custom") {
        address = saved.get(1).cloned().unwrap_or_default();
    }
    if address.is_empty() && interactive() {
        address = ask_for_custom_address().unwrap_or_default();
        if !address.is_empty() {
            save(&saved_server_file(), &format!("custom\n{address}\n"));
        }
    }
    if address.is_empty() {
        return Err(
            "buck2 builds on a NativeLink server of your own, and nothing says where it is. Set\n\
             BE3_BUILD_SERVER_ADDRESS to its host:port, such as 127.0.0.1:50052."
                .to_owned(),
        );
    }
    if !is_address(&address) {
        return Err(format!(
            "The custom build server's address is {address}, which is not a host:port."
        ));
    }
    Ok(address)
}

/// `Authorization: Bearer` with nl.be3.pfg.pw's token (BE3_NL_TOKEN, `.nl-token` or ~/.config/be3/nl-token), asking at
/// a terminal; empty when there is none.
fn bearer_header(server: &str) -> String {
    let what = format!("{server} token");
    let saved = Saved {
        variable: "BE3_NL_TOKEN",
        name: "nl-token",
        what: &what,
        checkout: Some(repository()),
    };
    let why = format!(
        "buck2 builds on {server}, which needs its token (guides/build_server.md says where to get one)."
    );
    saved
        .stored()
        .or_else(|| saved.ask(&why))
        .map_or_else(String::new, |key| {
            let key = key.strip_prefix("Bearer ").unwrap_or(&key).trim();
            format!("Authorization:Bearer {key}")
        })
}

pub mod relay {
    use super::*;

    pub fn cksum(data: &[u8]) -> u32 {
        let mut crc: u32 = 0;
        let mut feed = |byte: u8| {
            crc ^= u32::from(byte) << 24;
            for _ in 0..8 {
                crc = if crc & 0x8000_0000 != 0 {
                    (crc << 1) ^ 0x04C1_1DB7
                } else {
                    crc << 1
                };
            }
        };
        for &byte in data {
            feed(byte);
        }
        let mut length = data.len() as u64;
        while length != 0 {
            feed((length & 0xff) as u8);
            length >>= 8;
        }
        !crc
    }

    /// Builds scripts/internal/re-relay if this source has not been built, and returns the binary and its version.
    fn build() -> Result<(PathBuf, u32)> {
        let source = repository().join("scripts/internal/re-relay");
        let go = Command::new("go").args(["env", "GOEXE"]).output();
        let suffix = match go {
            Ok(output) if output.status.success() => {
                String::from_utf8_lossy(&output.stdout).trim().to_owned()
            }
            _ => {
                return Err("go was not found on PATH. buck2 reaches the build server through scripts/internal/re-relay, \
                            which needs Go 1.24 or newer."
                    .to_owned());
            }
        };
        let mut files: Vec<PathBuf> = std::fs::read_dir(&source)
            .map_err(|error| format!("could not read {}: {error}", source.display()))?
            .filter_map(|entry| entry.ok().map(|entry| entry.path()))
            .filter(|path| path.is_file())
            .collect();
        files.sort();
        let mut contents = Vec::new();
        for file in &files {
            contents.extend(
                std::fs::read(file)
                    .map_err(|error| format!("could not read {}: {error}", file.display()))?,
            );
        }
        let version = cksum(&contents);
        let relay = repository().join(format!("target/tools/re-relay-{version}/re-relay{suffix}"));
        if !relay.is_file() {
            let directory = relay.parent().unwrap_or(repository());
            std::fs::create_dir_all(directory)
                .map_err(|error| format!("could not create {}: {error}", directory.display()))?;
            let partial = crate::partial_path(&relay);
            let built = Command::new("go")
                .args(["build", "-trimpath", "-o"])
                .arg(&partial)
                .arg(".")
                .current_dir(&source)
                .status()
                .is_ok_and(|status| status.success());
            if !built {
                return Err(format!("could not build {}", source.display()));
            }
            std::fs::rename(&partial, &relay)
                .map_err(|error| format!("could not write {}: {error}", relay.display()))?;
        }
        Ok((relay, version))
    }

    /// Starts, or finds running, two relays to `upstream`, one for buck2's executions and one for its storage, and
    /// returns their local addresses. `tunnel` sends every call through the upstream's tunnel (re-relay's `-tunnel`).
    pub fn ensure(upstream: &str, tunnel: bool) -> Result<(String, String)> {
        let (relay, version) = build()?;
        let path = repository().to_string_lossy().into_owned();
        let port = 20000 + cksum(path.as_bytes()) % 2000 * 2;
        let engine_address = format!("127.0.0.1:{port}");
        let storage_address = format!("127.0.0.1:{}", port + 1);
        let log = repository().join("target/re-relay.log");
        for listen in [&engine_address, &storage_address] {
            let started = Command::new(&relay)
                .args(["ensure", "-listen", listen, "-upstream", upstream])
                .arg(format!("-tunnel={tunnel}"))
                .arg("-version")
                .arg(format!("{version}-{upstream}-{tunnel}"))
                .arg("-log")
                .arg(&log)
                .status()
                .is_ok_and(|status| status.success());
            if !started {
                return Err(format!(
                    "could not start the relay to {upstream} on {listen}"
                ));
            }
        }
        Ok((engine_address, storage_address))
    }
}
