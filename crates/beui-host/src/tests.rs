pub(crate) fn flashed(output: &crate::native::FrameOutput, bounds: Rect, color: Color32) -> bool {
    output.main().shapes().iter().any(|shape| {
        matches!(
            shape,
            crate::painter::Shape::Rect {
                rect,
                stroke_width,
                color: painted,
                ..
            } if *rect == bounds
                && *stroke_width > 0.0
                && painted.to_array()[..3] == color.to_array()[..3]
        )
    })
}

