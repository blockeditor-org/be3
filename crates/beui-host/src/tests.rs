    pub(crate) fn drag_and_rest(&mut self, from: Pos2, to: Pos2) {
        self.down(from, PointerButton::Primary);
        for step in 1..=8 {
            self.hover(from + (to - from) * (step as f32 / 8.0));
        }
        self.pause(Duration::from_millis(200));
        self.up(to, PointerButton::Primary);
        self.settle();
    }

    pub(crate) fn finger_drag(&mut self, path: &[Pos2]) {
        let (Some(first), Some(last)) = (path.first(), path.last()) else {
            return;
        };
        self.touch(TouchPhase::Start, *first);
        for point in &path[1..] {
            self.touch(TouchPhase::Move, *point);
        }
        self.touch(TouchPhase::End, *last);
    }

    pub(crate) fn finger_drag_and_hold(&mut self, from: Pos2, to: Pos2) {
        const STEP: f32 = 10.0;
        const HOLD: Duration = Duration::from_millis(200);
        self.touch(TouchPhase::Start, from);
        let steps = ((to - from).length() / STEP).ceil().max(1.0) as usize;
        for step in 1..=steps {
            self.touch(
                TouchPhase::Move,
                from + (to - from) * (step as f32 / steps as f32),
            );
        }
        self.pause(HOLD);
        self.touch(TouchPhase::End, to);
    }

