pub(crate) fn prompt_and_late<T>(run: impl Fn() -> T) -> (T, T) {
    struct Prompt;
    impl Drop for Prompt {
        fn drop(&mut self) {
            crate::native::testing::delay_measurement(false);
        }
    }
    let _prompt = Prompt;
    crate::native::testing::delay_measurement(false);
    let prompt = run();
    crate::native::testing::delay_measurement(true);
    (prompt, run())
}

