pub(crate) fn dialog_dock(tabs: Vec<u64>, dialogs: Dialogs) -> DialogDock {
    let dock = NodeRef::new();
    let pressed = create_signal(Vec::new());
    let keyed = create_signal(Vec::new());
    let attended = create_signal(Vec::new());
    let layout = dock::unstyled::DockingLayout::new();
    let owned_dialogs = crate::reactive::OwnedSignal::new(dialogs);
    let listed = owned_dialogs.handle();
    let document = build_node(move || {
        let keys = crate::reactive::create_memo(move || {
            listed.with(|listed| {
                listed
                    .iter()
                    .map(|(id, parent, _)| (*id, *parent))
                    .collect::<Vec<_>>()
            })
        });
        view! {
            <dock::styled::Docking @node_ref=&dock layout>
                <dock::unstyled::DockPane id="tabs">
                    <ForEach keys={tabs.clone()}>|id: u64|
                        <dock::unstyled::DockTab id title={format!("Tab {id}")}>
                            <FocusPanel
                                name={format!("content.{id}")}
                                owner=id
                                pressed={pressed}
                                keyed={keyed}
                                attended={None}
                                size={None}
                            />
                        </dock::unstyled::DockTab>
                    </ForEach>
                </dock::unstyled::DockPane>
                <ForEach keys>|(id, parent): (u64, u64)| {
                    let modal = crate::reactive::create_memo(move || {
                        listed.with(|listed| listed.iter().any(|(held, _, modal)| *held == id && *modal))
                    });
                    view! {
                        <dock::unstyled::DockDialog
                            id
                            parent
                            modal
                            title={format!("Dialog {id}")}
                            size={dialog_size(id)}
                        >
                            <FocusPanel
                                name={format!("dialog.{id}.field")}
                                owner=id
                                pressed={pressed}
                                keyed={keyed}
                                attended={Some(attended)}
                                size={Some(dialog_size(id))}
                            />
                        </dock::unstyled::DockDialog>
                    }
                }</ForEach>
            </dock::styled::Docking>
        }
    });
    DialogDock {
        document,
        dock: dock.get(),
        layout,
        pressed,
        keyed: keyed.read_only(),
        attended: attended.read_only(),
        dialogs: listed,
        _dialogs: owned_dialogs,
    }
}

#[component]
fn FocusPanel(
    name: String,
    owner: u64,
    pressed: Signal<Vec<u64>>,
    keyed: Signal<Vec<u64>>,
    attended: Option<Signal<Vec<u64>>>,
    size: Option<Vec2>,
) -> NodeId {
    if let (Some(attended), Some(tab)) = (attended, dock::unstyled::use_dock_tab()) {
        let called = crate::reactive::create_memo(move || tab.attention());
        crate::reactive::create_effect(move || {
            if called.get().is_some() {
                attended.update(|attended| attended.push(owner));
            }
        });
    }
    let width = size.map(|size| size.x);
    let height = size.map(|size| size.y);
    view! {
        <Interactive
            focusable=true
            @test_id={name}
            on_press={move |_: beui::PointerPress| pressed.update(|pressed| pressed.push(owner))}
            on_key={move |press: beui::KeyPress| {
                if press.pressed {
                    keyed.update(|keyed| keyed.push(owner));
                }
                true
            }}
        >
            <Frame width=width height=height />
        </Interactive>
    }
}

