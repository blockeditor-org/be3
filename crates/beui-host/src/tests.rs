const BLINK: Duration = Duration::from_millis(530);

fn blinking() -> crate::reactive::Draw {
    Rc::new(|painter: &Painter, rect: Rect| {
        painter.rect_filled(rect, 0.0, Color32::WHITE);
        core_painter(painter).ctx().request_repaint_after(BLINK);
    })
}

fn still() -> crate::reactive::Draw {
    Rc::new(|painter: &Painter, rect: Rect| {
        painter.rect_filled(rect, 0.0, Color32::WHITE);
    })
}

fn counted(
    document: &mut Document,
    node: impl Into<NodeId>,
) -> (ReadSignal<usize>, ReadSignal<usize>) {
    let counts = counted_with_measures(document, node);
    (counts.layouts, counts.paints)
}

fn counted_with_measures(document: &mut Document, node: impl Into<NodeId>) -> Counts {
    let node = node.into();
    let layouts = create_signal(0);
    let paints = create_signal(0);
    let measures = create_signal(0);
    let visits = create_signal(0);
    let inner = document.arena.take(node);
    document.arena.put_back(
        node,
        Box::new(Counted {
            inner,
            layouts,
            paints,
            measures,
            visits,
        }),
    );
    Counts {
        layouts: layouts.read_only(),
        paints: paints.read_only(),
        measures: measures.read_only(),
        visits,
    }
}

