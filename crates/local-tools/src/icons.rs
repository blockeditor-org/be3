use std::collections::{BTreeMap, HashSet};
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use serde_json::Value;

const LIST: &str = "crates/lucide/src/list.rs";
const FONT: &str = "crates/beui-font-freetype/src/assets/icons/lucide.ttf";

pub fn main(arguments: Vec<String>) -> ExitCode {
    let [package] = arguments.as_slice() else {
        eprintln!(
            "usage: local-tools icons PACKAGE\n\
             PACKAGE is lucide-static unpacked (npm pack lucide-static@VERSION, then tar xzf), \
             whose icons, tags and font replace beui_core::icons"
        );
        return ExitCode::FAILURE;
    };
    match regenerate(Path::new(package)) {
        Ok(summary) => {
            println!("{summary}");
            ExitCode::SUCCESS
        }
        Err(error) => {
            eprintln!("{error}");
            ExitCode::FAILURE
        }
    }
}

fn regenerate(package: &Path) -> Result<String, String> {
    let root = repository()?;
    let version = read(&package.join("package.json"))?["version"]
        .as_str()
        .ok_or("package.json names no version")?
        .to_owned();
    let list = list(&version, package)?;
    let count = list
        .lines()
        .filter(|line| line.starts_with("    ICON_"))
        .count();
    std::fs::write(root.join(LIST), list).map_err(|error| format!("writing {LIST}: {error}"))?;
    std::fs::copy(package.join("font/lucide.ttf"), root.join(FONT))
        .map_err(|error| format!("copying the font to {FONT}: {error}"))?;
    Ok(format!(
        "wrote {count} icons from lucide-static {version} to {LIST} and its font to {FONT}"
    ))
}

fn repository() -> Result<PathBuf, String> {
    let here = std::env::current_dir().map_err(|error| error.to_string())?;
    here.ancestors()
        .find(|dir| dir.join(".buckconfig").is_file() && dir.join("crates/beui-core").is_dir())
        .map(Path::to_path_buf)
        .ok_or_else(|| format!("{} is not inside the repository", here.display()))
}

fn read(path: &Path) -> Result<Value, String> {
    let text = std::fs::read_to_string(path)
        .map_err(|error| format!("reading {}: {error}", path.display()))?;
    serde_json::from_str(&text).map_err(|error| format!("parsing {}: {error}", path.display()))
}

fn list(version: &str, package: &Path) -> Result<String, String> {
    let nodes = read(&package.join("icon-nodes.json"))?;
    let names: HashSet<&str> = nodes
        .as_object()
        .ok_or("icon-nodes.json is not an object")?
        .keys()
        .map(String::as_str)
        .collect();
    let codepoints: BTreeMap<String, u64> =
        serde_json::from_value(read(&package.join("font/codepoints.json"))?)
            .map_err(|error| format!("font/codepoints.json: {error}"))?;
    let tags: BTreeMap<String, Vec<String>> =
        serde_json::from_value(read(&package.join("tags.json"))?)
            .map_err(|error| format!("tags.json: {error}"))?;
    let mut aliases: BTreeMap<u64, Vec<&str>> = BTreeMap::new();
    for (name, codepoint) in &codepoints {
        if !names.contains(name.as_str()) {
            aliases.entry(*codepoint).or_default().push(name);
        }
    }
    let mut sorted: Vec<&str> = names.into_iter().collect();
    sorted.sort_unstable();
    let mut out = format!(
        "// Generated by `local-tools icons` from lucide-static {version} (guides/beui.md): each icon's\n\
         // constant, Lucide name and codepoint, then its tags and the older names it had. @yeskeepfile\n\
         icons! {{\n"
    );
    for name in sorted {
        let codepoint = *codepoints
            .get(name)
            .ok_or_else(|| format!("{name} has no codepoint in font/codepoints.json"))?;
        let words: Vec<&str> = tags
            .get(name)
            .into_iter()
            .flatten()
            .map(String::as_str)
            .chain(aliases.get(&codepoint).into_iter().flatten().copied())
            .collect();
        let constant = format!("ICON_{}", name.to_uppercase().replace('-', "_"));
        out.push_str(&format!(
            "    {constant} {name:?} \"\\u{{{codepoint:x}}}\" {:?};\n",
            words.join(", ")
        ));
    }
    out.push_str("}\n");
    Ok(out)
}
