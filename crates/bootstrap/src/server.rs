const SERVERS: [&str; 5] = [
    "namespace",
    "api.be3.pfg.pw",
    "blocks.pfg.pw",
    "buildbuddy",
    "local",
];
const NAMESPACE_URL: &str = "https://api.be3.pfg.pw/build/namespace";
const MARKER: &str = "# @generated by ./scripts/buck: where buck2 reaches the build server.";

pub fn configure(buck2: &Path) -> Result<()> {
    let path = repository().join(".buckconfig.local");
    if let Ok(existing) = std::fs::read_to_string(&path)
        && !existing
            .lines()
            .next()
            .unwrap_or_default()
            .contains("@generated by ./scripts/")
    {
        eprintln!(".buckconfig.local was written by hand, so buck2 is left to reach the build");
        eprintln!("server it names.");
        return Ok(());
    }
    let mut proxy = std::env::var("HTTPS_PROXY")
        .ok()
        .filter(|value| !value.is_empty())
        .or_else(|| {
            std::env::var("https_proxy")
                .ok()
                .filter(|value| !value.is_empty())
        });
    let server = server()?;
    let (engine, storage, header);
    let (mut engine_address, mut storage_address, mut tls);
    if server == "local" {
        engine = local_address()?;
        storage = engine.clone();
        engine_address = engine.clone();
        storage_address = engine.clone();
        header = String::new();
        tls = false;
        proxy = None;
    } else {
        if server == "namespace" {
            let config = namespace::ask()?;
            engine = config.host("engine_address");
            storage = config.host("cas_address");
            header = config.header();
        } else if server == "buildbuddy" {
            let key = key(&server)?;
            engine = "remote.buildbuddy.io".to_owned();
            storage = engine.clone();
            header = format!("x-buildbuddy-api-key:{key}");
        } else {
            engine = server.clone();
            storage = engine.clone();
            header = gateway_header(&server);
        }
        engine_address = format!("{engine}:443");
        storage_address = format!("{storage}:443");
        tls = true;
    }
    if proxy.is_some() {
        let (engine_relay, storage_relay) = relay::ensure(&engine, &storage)?;
        engine_address = engine_relay;
        storage_address = storage_relay;
        tls = false;
    }

    let mut config = String::new();
    let _ = writeln!(config, "{MARKER}");
    let _ = writeln!(config, "# The executor: {engine}");
    let _ = writeln!(config, "# The storage: {storage}");
    let _ = writeln!(config, "[buck2_re_client]");
    let _ = writeln!(config, "action_cache_address = {storage_address}");
    let _ = writeln!(config, "cas_address = {storage_address}");
    let _ = writeln!(config, "engine_address = {engine_address}");
    if !header.is_empty() {
        let _ = writeln!(config, "http_headers = {header}");
    }
    let _ = writeln!(config, "tls = {tls}");
    let _ = writeln!(config, "[be3]");
    let _ = writeln!(config, "build_server = {server}");
    if std::fs::read(&path).is_ok_and(|existing| existing == config.as_bytes()) {
        return Ok(());
    }
    write_private(&path, &config)?;
    let _ = Command::new(buck2)
        .arg("kill")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
    Ok(())
}

fn write_private(path: &Path, text: &str) -> Result<()> {
    save_private(path, text).map_err(|error| format!("could not write {}: {error}", path.display()))
}

fn saved_server_file() -> PathBuf {
    config_directory().join("build-server")
}

fn saved_lines() -> Vec<String> {
    std::fs::read_to_string(saved_server_file())
        .unwrap_or_default()
        .lines()
        .map(|line| {
            line.chars()
                .filter(|character| !character.is_whitespace())
                .collect()
        })
        .collect()
}

fn server() -> Result<String> {
    let saved = saved_server_file();
    let mut server = std::env::var("BE3_BUILD_SERVER").unwrap_or_default();
    if server.is_empty() {
        server = saved_lines().into_iter().next().unwrap_or_default();
    }
    if server.is_empty() {
        server = ask_for_server(&saved).unwrap_or_default();
    }
    if server.is_empty() {
        server = "namespace".to_owned();
    }
    if SERVERS.contains(&server.as_str()) {
        return Ok(server);
    }
    Err(format!(
        "The build server is {server}, which is none of {}.\nBE3_BUILD_SERVER or {} picks it.",
        SERVERS.join(" "),
        saved.display()
    ))
}

fn ask_for_server(saved: &Path) -> Option<String> {
    let choices: Vec<Choice> = SERVERS
        .iter()
        .map(|server| Choice {
            label: server,
            detail: match *server {
                "namespace" => "Namespace's remote execution",
                "api.be3.pfg.pw" => "our own NativeLink server",
                "blocks.pfg.pw" => "our NativeLink build VM, behind blocks.pfg.pw",
                "buildbuddy" => "BuildBuddy's remote.buildbuddy.io",
                _ => "a NativeLink server of your own, without TLS or a key",
            },
        })
        .collect();
    if interactive() {
        eprintln!("guides/build_server.md says more about each.");
    }
    let server = SERVERS[choose("Which build server should buck2 build on?", &choices, 0)?];
    let mut text = format!("{server}\n");
    if server == "local" {
        text.push_str(&format!("{}\n", ask_for_local_address()?));
    }
    save(saved, &text);
    eprintln!(
        "Saved it to {}; delete it to be asked again.",
        saved.display()
    );
    Some(server.to_owned())
}

fn save(path: &Path, text: &str) {
    if let Err(error) = write_private(path, text) {
        eprintln!("{error}");
    }
}

fn is_address(address: &str) -> bool {
    address.split_once(':').is_some_and(|(host, port)| {
        !host.is_empty()
            && !host.contains('/')
            && !port.is_empty()
            && port.chars().all(|character| character.is_ascii_digit())
    })
}

fn ask_for_local_address() -> Option<String> {
    text("NativeLink address:", "127.0.0.1:50052", |address| {
        let address = address.strip_prefix("grpc://").unwrap_or(address);
        if is_address(address) {
            Ok(address.to_owned())
        } else {
            Err("That is not a host:port.".to_owned())
        }
    })
}

fn local_address() -> Result<String> {
    let mut address = std::env::var("BE3_BUILD_SERVER_ADDRESS").unwrap_or_default();
    let saved = saved_lines();
    if address.is_empty() && saved.first().is_some_and(|server| server == "local") {
        address = saved.get(1).cloned().unwrap_or_default();
    }
    if address.is_empty() && interactive() {
        address = ask_for_local_address().unwrap_or_default();
        if !address.is_empty() {
            save(&saved_server_file(), &format!("local\n{address}\n"));
        }
    }
    if address.is_empty() {
        return Err(
            "buck2 builds on a local NativeLink server, and nothing says where it is. Set\n\
                    BE3_BUILD_SERVER_ADDRESS to its host:port, such as 127.0.0.1:50052."
                .to_owned(),
        );
    }
    if !is_address(&address) {
        return Err(format!(
            "The local build server's address is {address}, which is not a host:port."
        ));
    }
    Ok(address)
}

fn key(server: &str) -> Result<String> {
    let name = format!("build-server-key.{server}");
    let what = format!("{server} key");
    let saved = Saved {
        variable: "BE3_BUILD_SERVER_KEY",
        name: &name,
        what: &what,
        checkout: Some(repository()),
    };
    if let Some(key) = saved.stored() {
        return Ok(key);
    }
    let why = format!(
        "buck2 builds on {server}, and needs its key. guides/build_server.md says where to get one."
    );
    if let Some(key) = saved.ask(&why) {
        return Ok(key);
    }
    Err(format!(
        "buck2 builds on {server}, and there is no key for it. Set\n\
         BE3_BUILD_SERVER_KEY, or write the key to .{name} at the root of the\n\
         checkout or to ~/.config/be3/{name}. Run ./scripts/buck from a terminal\n\
         to be asked for it. guides/build_server.md has more."
    ))
}

fn gateway_header(server: &str) -> String {
    let why = format!(
        "buck2 builds on {server}, behind the gateway, so it needs the whole value of\n\
         the Be3-Gateway-Authorization header, such as \"Bearer KEY\" (guides/build_server.md)."
    );
    gateway()
        .stored()
        .or_else(|| gateway().ask(&why))
        .map_or_else(String::new, |key| {
            format!("Be3-Gateway-Authorization:{key}")
        })
}

pub fn gateway() -> Saved<'static> {
    Saved {
        variable: "BE3_AUTHORIZATION",
        name: "gateway-authorization",
        what: "api.be3.pfg.pw gateway key",
        checkout: Some(repository()),
    }
}

mod namespace {
    use super::*;

    pub struct Config(String);

    impl Config {
        pub fn host(&self, name: &str) -> String {
            self.value(name)
                .map(|value| {
                    let value = value
                        .strip_prefix("grpcs://")
                        .or_else(|| value.strip_prefix("grpc://"))
                        .unwrap_or(value);
                    value
                        .split([':', '/'])
                        .next()
                        .unwrap_or_default()
                        .to_owned()
                })
                .unwrap_or_default()
        }

        pub fn header(&self) -> String {
            self.value("http_headers").unwrap_or_default().to_owned()
        }

        fn value(&self, name: &str) -> Option<&str> {
            self.0.lines().find_map(|line| {
                let rest = line.strip_prefix(name)?.trim_start_matches(' ');
                Some(rest.strip_prefix('=')?.trim_start_matches(' '))
            })
        }

        fn complete(&self) -> bool {
            !self.host("engine_address").is_empty()
                && !self.host("cas_address").is_empty()
                && !self.header().is_empty()
        }
    }

    pub fn ask() -> Result<Config> {
        let (mut status, mut body) = wake(gateway().stored())?;
        let mut asked = false;
        while status == "401" || status == "403" {
            let why = if asked {
                format!(
                    "The gateway refused that key too ({status}). Enter it again, or press Esc to stop."
                )
            } else {
                format!(
                    "The gateway in front of {NAMESPACE_URL} refused the request ({status}), so it needs\n\
                     the whole value of the Be3-Gateway-Authorization header, such as\n\
                     \"Bearer KEY\" (guides/build_server.md)."
                )
            };
            asked = true;
            let Some(key) = gateway().ask(&why) else {
                break;
            };
            (status, body) = wake(Some(key))?;
        }
        if status != "200" {
            eprintln!("{body}");
            if status == "401" || status == "403" {
                return Err(format!(
                    "The gateway in front of {NAMESPACE_URL} refused this request. Set\n\
                     BE3_AUTHORIZATION to its Be3-Gateway-Authorization header, or run\n\
                     ./scripts/buck at a terminal to be asked for it (guides/build_server.md)."
                ));
            }
            return Err(format!(
                "{NAMESPACE_URL} answered {status} rather than the cluster's hosts (guides/build_server.md)."
            ));
        }
        let config = Config(body);
        if !config.complete() {
            return Err(format!(
                "{NAMESPACE_URL} answered with a configuration that does not name the executor,\n\
                 the storage and the header buck2 needs:\n{}",
                config.0
            ));
        }
        Ok(config)
    }

    fn wake(key: Option<String>) -> Result<(String, String)> {
        let mut child = Command::new("curl")
            .args(["--silent", "--show-error", "--max-time", "600"])
            .args([
                "--header",
                "@-",
                "--write-out",
                "\n%{http_code}",
                NAMESPACE_URL,
            ])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::inherit())
            .spawn()
            .map_err(curl_error)?;
        if let Some(mut stdin) = child.stdin.take() {
            let header = key.map_or_else(String::new, |key| {
                format!("Be3-Gateway-Authorization: {key}\n")
            });
            let _ = stdin.write_all(header.as_bytes());
        }
        let (sender, receiver) = mpsc::channel();
        std::thread::spawn(move || {
            let _ = sender.send(child.wait_with_output());
        });
        let output = match receiver.recv_timeout(Duration::from_secs(2)) {
            Ok(output) => output,
            Err(_) => {
                eprintln!("Waking the remote execution cluster through {NAMESPACE_URL}...");
                receiver
                    .recv()
                    .map_err(|error| format!("could not run curl: {error}"))?
            }
        }
        .map_err(curl_error)?;
        if !output.status.success() {
            return Err(format!(
                "Could not reach {NAMESPACE_URL} (guides/build_server.md)."
            ));
        }
        let text = String::from_utf8_lossy(&output.stdout);
        let (body, status) = text.rsplit_once('\n').unwrap_or(("", &text));
        Ok((status.trim().to_owned(), body.to_owned()))
    }
}

pub mod relay {
    use super::*;

    pub fn cksum(data: &[u8]) -> u32 {
        let mut crc: u32 = 0;
        let mut feed = |byte: u8| {
            crc ^= u32::from(byte) << 24;
            for _ in 0..8 {
                crc = if crc & 0x8000_0000 != 0 {
                    (crc << 1) ^ 0x04C1_1DB7
                } else {
                    crc << 1
                };
            }
        };
        for &byte in data {
            feed(byte);
        }
        let mut length = data.len() as u64;
        while length != 0 {
            feed((length & 0xff) as u8);
            length >>= 8;
        }
        !crc
    }

    pub fn ensure(engine: &str, storage: &str) -> Result<(String, String)> {
        let source = repository().join("scripts/internal/re-relay");
        let go = Command::new("go").args(["env", "GOEXE"]).output();
        let suffix = match go {
            Ok(output) if output.status.success() => {
                String::from_utf8_lossy(&output.stdout).trim().to_owned()
            }
            _ => {
                return Err("go was not found on PATH. HTTPS_PROXY is set, and buck2 reaches the build server through \
                            it with scripts/internal/re-relay, which needs Go 1.24 or newer."
                    .to_owned());
            }
        };
        let mut files: Vec<PathBuf> = std::fs::read_dir(&source)
            .map_err(|error| format!("could not read {}: {error}", source.display()))?
            .filter_map(|entry| entry.ok().map(|entry| entry.path()))
            .filter(|path| path.is_file())
            .collect();
        files.sort();
        let mut contents = Vec::new();
        for file in &files {
            contents.extend(
                std::fs::read(file)
                    .map_err(|error| format!("could not read {}: {error}", file.display()))?,
            );
        }
        let version = cksum(&contents);
        let relay = repository().join(format!("target/tools/re-relay-{version}/re-relay{suffix}"));
        if !relay.is_file() {
            let directory = relay.parent().unwrap_or(repository());
            std::fs::create_dir_all(directory)
                .map_err(|error| format!("could not create {}: {error}", directory.display()))?;
            let partial = crate::partial_path(&relay);
            let built = Command::new("go")
                .args(["build", "-trimpath", "-o"])
                .arg(&partial)
                .arg(".")
                .current_dir(&source)
                .status()
                .is_ok_and(|status| status.success());
            if !built {
                return Err(format!("could not build {}", source.display()));
            }
            std::fs::rename(&partial, &relay)
                .map_err(|error| format!("could not write {}: {error}", relay.display()))?;
        }
        let path = repository().to_string_lossy().into_owned();
        let port = 20000 + cksum(path.as_bytes()) % 2000 * 2;
        let engine_address = format!("127.0.0.1:{port}");
        let storage_address = format!("127.0.0.1:{}", port + 1);
        let log = repository().join("target/re-relay.log");
        for (listen, upstream) in [(&engine_address, engine), (&storage_address, storage)] {
            let started = Command::new(&relay)
                .args([
                    "ensure",
                    "-listen",
                    listen,
                    "-upstream",
                    upstream,
                    "-version",
                ])
                .arg(format!("{version}-{upstream}"))
                .arg("-log")
                .arg(&log)
                .status()
                .is_ok_and(|status| status.success());
            if !started {
                return Err(format!(
                    "could not start the relay to {upstream} on {listen}"
                ));
            }
        }
        Ok((engine_address, storage_address))
    }
}
